#!/usr/bin/env python3
"""
Generates the launcher artwork.

One geometry is used for both the adaptive-icon vector (what the system actually draws) and the
PNG preview in docs/, so the README never shows something different from the installed app.

    python3 toolchain/make_icons.py

Requires Pillow only for the preview; the vector files are written without any dependency.
"""
from __future__ import annotations

import os
from typing import List, Tuple

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
DOCS = os.path.join(ROOT, "docs")

VIEWPORT = 108.0
# Keyboard slab inside the 66dp safe zone of the adaptive icon.
PANEL = (22.0, 31.0, 64.0, 45.0, 9.0)
KEY_HEIGHT = 6.6
KEY_RADIUS = 1.7

Rect = Tuple[float, float, float, float, float]  # x, y, w, h, r


def key_rows() -> List[Rect]:
    keys: List[Rect] = []
    left, right = 27.0, 81.0
    width = right - left
    gap = 1.2
    for y, count in ((36.6, 10), (45.3, 9), (54.0, 7)):
        kw = (width - gap * (count - 1)) / count
        for i in range(count):
            keys.append((left + i * (kw + gap), y, kw, KEY_HEIGHT, KEY_RADIUS))
    keys.append((27.0, 62.7, 9.5, KEY_HEIGHT, KEY_RADIUS))
    keys.append((39.5, 62.7, 31.0, KEY_HEIGHT, 3.3))
    keys.append((73.0, 62.7, 8.0, KEY_HEIGHT, KEY_RADIUS))
    return keys


def rounded_path(x: float, y: float, w: float, h: float, r: float) -> str:
    r = min(r, w / 2, h / 2)
    return (
        f"M{x + r:.3f},{y:.3f} "
        f"h{w - 2 * r:.3f} a{r:.3f},{r:.3f} 0 0 1 {r:.3f},{r:.3f} "
        f"v{h - 2 * r:.3f} a{r:.3f},{r:.3f} 0 0 1 -{r:.3f},{r:.3f} "
        f"h-{w - 2 * r:.3f} a{r:.3f},{r:.3f} 0 0 1 -{r:.3f},-{r:.3f} "
        f"v-{h - 2 * r:.3f} a{r:.3f},{r:.3f} 0 0 1 {r:.3f},-{r:.3f} z"
    )


def write_foreground() -> None:
    data = " ".join(rounded_path(*key) for key in key_rows())
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by toolchain/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">

    <path
        android:fillColor="#22FFFFFF"
        android:strokeColor="#57FFFFFF"
        android:strokeWidth="1.1"
        android:pathData="{rounded_path(*PANEL)}" />

    <path
        android:fillColor="#F0FFFFFF"
        android:pathData="{data}" />
</vector>
"""
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w") as handle:
        handle.write(xml)


def write_background() -> None:
    xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by toolchain/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">

    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="14"
                android:startY="6"
                android:endX="96"
                android:endY="104">
                <item android:offset="0" android:color="#FF7496FF" />
                <item android:offset="0.48" android:color="#FF8B79FF" />
                <item android:offset="1" android:color="#FFD68CFF" />
            </gradient>
        </aapt:attr>
    </path>

    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="24"
                android:centerY="16"
                android:gradientRadius="88">
                <item android:offset="0" android:color="#38FFFFFF" />
                <item android:offset="1" android:color="#00FFFFFF" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""
    with open(os.path.join(RES, "drawable", "ic_launcher_background.xml"), "w") as handle:
        handle.write(xml)


def write_preview() -> None:
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("Pillow is not installed, skipping the PNG preview")
        return

    size = 1024
    scale = size / VIEWPORT
    image = Image.new("RGBA", (size, size))
    pixels = image.load()
    starts = [(0x74, 0x96, 0xFF), (0x8B, 0x79, 0xFF), (0xD6, 0x8C, 0xFF)]
    x0, y0 = 14 * scale, 6 * scale
    x1, y1 = 96 * scale, 104 * scale
    dx, dy = x1 - x0, y1 - y0
    length = dx * dx + dy * dy
    for y in range(size):
        for x in range(size):
            t = max(0.0, min(1.0, ((x - x0) * dx + (y - y0) * dy) / length))
            a, b = (0, 1) if t < 0.48 else (1, 2)
            f = (t / 0.48) if t < 0.48 else ((t - 0.48) / 0.52)
            pixels[x, y] = tuple(int(starts[a][i] + (starts[b][i] - starts[a][i]) * f) for i in range(3)) + (255,)

    def layer(fn):
        nonlocal image
        overlay = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        fn(ImageDraw.Draw(overlay))
        image = Image.alpha_composite(image, overlay)

    def light(draw):
        for i in range(48, 0, -1):
            t = i / 48
            radius = 88 * scale * t
            draw.ellipse(
                [24 * scale - radius, 16 * scale - radius, 24 * scale + radius, 16 * scale + radius],
                fill=(255, 255, 255, int(44 * (1 - t) ** 1.7)),
            )

    layer(light)

    def panel(draw):
        px, py, pw, ph, pr = PANEL
        draw.rounded_rectangle(
            [px * scale, py * scale, (px + pw) * scale, (py + ph) * scale],
            radius=pr * scale, fill=(255, 255, 255, 34), outline=(255, 255, 255, 86), width=max(1, int(1.1 * scale)),
        )

    layer(panel)

    def shadows(draw):
        for kx, ky, kw, kh, kr in key_rows():
            draw.rounded_rectangle(
                [kx * scale, (ky + 0.55) * scale, (kx + kw) * scale, (ky + kh + 0.55) * scale],
                radius=kr * scale, fill=(40, 40, 90, 26),
            )

    layer(shadows)

    def keys(draw):
        for kx, ky, kw, kh, kr in key_rows():
            draw.rounded_rectangle(
                [kx * scale, ky * scale, (kx + kw) * scale, (ky + kh) * scale],
                radius=kr * scale, fill=(255, 255, 255, 240),
            )

    layer(keys)

    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size, size], radius=int(size * 0.225), fill=255)
    image.putalpha(mask)
    image.save(os.path.join(DOCS, "icon.png"))

    # Legacy densities, in case a launcher asks for a raster icon.
    for folder, px in (
        ("mipmap-mdpi", 48), ("mipmap-hdpi", 72), ("mipmap-xhdpi", 96),
        ("mipmap-xxhdpi", 144), ("mipmap-xxxhdpi", 192),
    ):
        target = os.path.join(RES, folder)
        os.makedirs(target, exist_ok=True)
        image.resize((px, px), Image.LANCZOS).save(os.path.join(target, "ic_launcher.png"))
        image.resize((px, px), Image.LANCZOS).save(os.path.join(target, "ic_launcher_round.png"))


if __name__ == "__main__":
    os.makedirs(os.path.join(RES, "drawable"), exist_ok=True)
    os.makedirs(DOCS, exist_ok=True)
    write_background()
    write_foreground()
    write_preview()
    print("Launcher artwork written to", RES, "and", DOCS)
